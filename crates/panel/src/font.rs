//! The controller's own character set, codes 0x20 to 0x7F of the HD44780
//! A00 ROM, as seven rows of five bits; the eighth row is the cursor's and
//! stays empty. The renders draw text with it; the glass has it built in.

/// The rows of a code, or of `?` for a code outside the set; user glyphs
/// (0 to 7) and the block (0xFF) are not here.
pub fn rows(code: u8) -> [u8; 8] {
    let index = match code {
        0x20..=0x7F => (code - 0x20) as usize,
        _ => (b'?' - 0x20) as usize,
    };
    let r = FONT[index];
    [r[0], r[1], r[2], r[3], r[4], r[5], r[6], 0]
}

