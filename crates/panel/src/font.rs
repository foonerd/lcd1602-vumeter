#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_code_has_five_bit_rows_and_unknown_codes_read_as_a_question_mark() {
        for code in 0x20..=0x7Fu8 {
            assert!(rows(code).iter().all(|r| *r < 32), "code {code:#04x}");
        }
        assert_eq!(rows(0x80), rows(b'?'));
        assert_eq!(rows(b'L')[6], 0b11111);
        assert_eq!(rows(b' '), [0; 8]);
    }
}
